var KEYS = Object.keys(LEXICON).sort(function (a, b) {
  return b.length - a.length;
});
var KANJI = /[㐀-鿿々]/;

// 文字列のよみ（ひらがな）。辞書で読めない漢字があれば例外
function yomi(str) {
  var out = "";
  var i = 0;
  while (i < str.length) {
    var hit = null;
    for (var k = 0; k < KEYS.length; k++) {
      if (str.startsWith(KEYS[k], i)) {
        hit = KEYS[k];
        break;
      }
    }
    if (hit) {
      out += LEXICON[hit];
      i += hit.length;
    } else {
      if (KANJI.test(str[i])) throw new Error("よみが分からない漢字「" + str[i] + "」: " + str);
      out += str[i];
      i++;
    }
  }
  return out;
}

