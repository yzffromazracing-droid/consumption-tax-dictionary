var BY_FIRST = {};
Object.keys(LEXICON)
  .sort(function (a, b) {
    return b.length - a.length;
  })
  .forEach(function (key) {
    (BY_FIRST[key[0]] = BY_FIRST[key[0]] || []).push(key);
  });
var KANJI = /[\u3400-\u9FFF々]/;

/*
 * 文字列のよみ（ひらがな）。辞書にない漢字があれば例外。
 * 区切り方は「辞書の語の数がいちばん少ない」ものを選ぶ（単純な最長一致だと
 * 「工業用水道業」を 工業+用水+道 と区切って行き詰まるため）。同数なら先頭の語が長いほうを選ぶ。
 */
function yomi(str) {
  var n = str.length;
  var cost = new Array(n + 1);
  var pick = new Array(n + 1);
  cost[n] = 0;
  for (var i = n - 1; i >= 0; i--) {
    cost[i] = Infinity;
    (BY_FIRST[str[i]] || []).forEach(function (key) {
      if (!str.startsWith(key, i)) return;
      var c = 1 + cost[i + key.length];
      if (c < cost[i]) {
        cost[i] = c;
        pick[i] = key;
      }
    });
    // 漢字以外（かな・英数字・記号）は辞書になくてもそのまま残せる
    if (!KANJI.test(str[i]) && cost[i + 1] < cost[i]) {
      cost[i] = cost[i + 1];
      pick[i] = null;
    }
  }
  if (cost[0] === Infinity) {
    for (var j = 0; j < n; j++) {
      if (cost[j] === Infinity && KANJI.test(str[j])) throw new Error("よみが分からない漢字「" + str[j] + "」: " + str);
    }
    throw new Error("よみを作れません: " + str);
  }
  var out = "";
  var k = 0;
  while (k < n) {
    if (pick[k]) {
      out += LEXICON[pick[k]];
      k += pick[k].length;
    } else {
      out += str[k];
      k++;
    }
  }
  return out;
}

